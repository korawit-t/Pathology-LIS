BACKFILL_CYTO = """
UPDATE {reports} r
SET images_snapshot = COALESCE((
    SELECT json_agg(json_build_object(
        'image_url', i.image_url,
        'description', COALESCE(i.description, '')
    ) ORDER BY i."order", i.id)
    FROM {images} i
    WHERE i.case_id = r.case_id AND i.show_in_report
), '[]'::json)
WHERE r.images_snapshot IS NULL
  AND r.case_id IS NOT NULL
"""


